#!/usr/bin/env node
// Regenerates src/migrations.generated.ts from migrations/*.sql (the reviewed source of truth).
// Why embedded: bundlers (Next/webpack) can't follow `new URL("../migrations/", import.meta.url)`
// to a directory, so the web build failed. A drift test keeps the two identical.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "migrations");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();
const entries = files.map((name) => ({
  name,
  sql: readFileSync(join(dir, name), "utf8").replace(/\r\n/g, "\n"),
}));
const out = `// GENERATED by scripts/embed-migrations.mjs from migrations/*.sql. Do not edit by hand.
// Regenerate: node packages/persistence/scripts/embed-migrations.mjs (a test checks for drift).
export const MIGRATIONS: ReadonlyArray<{ readonly name: string; readonly sql: string }> = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(root, "src", "migrations.generated.ts"), out);
console.log(`embedded ${files.length} migration(s)`);
